    function randomLink() {
        const id = TARGET_IDS[Math.floor(Math.random() * TARGET_IDS.length)];
        return 'https://www.torn.com/profiles.php?XID=' + id;
    }

    function openRandomTarget(e) {
        e.preventDefault();
        window.open(randomLink(), '_blank', 'noopener');
    }

    function buildButton() {
        const a = document.createElement('a');
        a.id = BTN_ID;
        a.href = '#';
        a.className = 'profile-button';
        a.title = 'Open a random chain target';
        a.setAttribute('aria-label', 'Open a random chain target');
        a.style.cssText = 'display:inline-flex;align-items:center;justify-content:center;' +
                          'min-width:40px;cursor:pointer;font-weight:bold;text-decoration:none;';
        a.textContent = '🎯';
        a.addEventListener('click', openRandomTarget);
        return a;
    }

    function findContainer() {
        // Torn has changed this markup over time; try the known variants.
        return document.querySelector('.profile-buttons .buttons-list') ||
               document.querySelector('.buttons-wrap .buttons-list') ||
               document.querySelector('.buttons-list');
    }

    function inject() {
        if (document.getElementById(BTN_ID)) return true;
        const container = findContainer();
        if (!container) return false;
        container.appendChild(buildButton());
        return true;
    }

    function addFloatingFallback() {
        if (document.getElementById(BTN_ID)) return;
        const btn = buildButton();
        btn.style.cssText += 'position:fixed;bottom:16px;right:16px;z-index:99999;' +
                             'width:44px;height:44px;border-radius:50%;background:#333;color:#fff;' +
                             'box-shadow:0 2px 6px rgba(0,0,0,.5);font-size:20px;';
        document.body.appendChild(btn);
    }

    // The profile renders asynchronously and re-renders on navigation,
    // so watch the DOM and re-inject if the button disappears.
    function start() {
        inject();
        const observer = new MutationObserver(() => {
            if (!document.getElementById(BTN_ID)) inject();
        });
        observer.observe(document.body, { childList: true, subtree: true });

        // If the buttons list never shows up, fall back to a floating button.
        setTimeout(() => { if (!document.getElementById(BTN_ID)) addFloatingFallback(); }, 5000);
    }

    if (document.body) start();
    else document.addEventListener('DOMContentLoaded', start);
